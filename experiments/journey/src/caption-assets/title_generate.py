#!/usr/bin/env python3
"""Generate the Journey title outlines in the Omarchy mono face.

Reuses generate.py's FreeType reader. Input: JetBrains Mono (Nerd Font build
as shipped by Omarchy), Bold for theme names and Regular for the label.
Sizes follow the approved mock at 1920 x 1080: 34 px names, 12.5 px label.
"""
import argparse
import ctypes as C
import hashlib
import textwrap
from pathlib import Path

import generate as G


def outline(ft, library, font, text, size, tracking):
    face = C.POINTER(G.Face)()
    G.checked(ft.FT_New_Face(library, str(font).encode(), 0, C.byref(face)))
    try:
        G.checked(ft.FT_Select_Charmap(face, 0x756E6963))
        return G.text_outline(ft, face, text, size, tracking)[0]
    finally:
        ft.FT_Done_Face(face)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--bold", type=Path, default=Path("/usr/share/fonts/TTF/JetBrainsMonoNerdFont-Bold.ttf"))
    p.add_argument("--regular", type=Path, default=Path("/usr/share/fonts/TTF/JetBrainsMonoNerdFont-Regular.ttf"))
    p.add_argument("--output", type=Path, default=Path(__file__).with_name("title-outlines.inc"))
    a = p.parse_args()
    ft = G.freetype()
    library = C.c_void_p()
    G.checked(ft.FT_Init_FreeType(C.byref(library)))
    out = ["// Generated by title_generate.py; do not edit. Fixed title artwork only.",
           "// Outlines derived from JetBrains Mono (SIL OFL 1.1); see README.md.",
           f"// Bold SHA-256: {hashlib.sha256(a.bold.read_bytes()).hexdigest()}",
           f"// Regular SHA-256: {hashlib.sha256(a.regular.read_bytes()).hexdigest()}"]
    for name, text, font, size, tracking in (
        ("titleLabel", "OMARCHY THEME", a.regular, 12.5, 0.6),
        ("titleOsaka", "Osaka Jade", a.bold, 34, 0),
        ("titleKanagawa", "Kanagawa", a.bold, 34, 0),
        ("titleTokyo", "Tokyo Night", a.bold, 34, 0),
    ):
        data = outline(ft, library, font, text, size, tracking)
        out.append(f"\nconstexpr char {name}[] =")
        lines = textwrap.wrap(data, width=110, break_long_words=False, break_on_hyphens=False)
        out.extend(f'    "{l}{" " if i < len(lines) - 1 else ""}"' for i, l in enumerate(lines))
        out[-1] += ";"
    ft.FT_Done_FreeType(library)
    a.output.write_text("\n".join(out) + "\n")
    print("wrote", a.output)


if __name__ == "__main__":
    main()
