#!/usr/bin/env python3
"""Generate the Osaka Jade sign lettering (one glyph per outline).

Reuses generate.py's FreeType reader. Input: Noto Sans CJK (Japanese face,
index 0 of the collection). Each glyph is emitted at 1 px per em so the
scene scales it freely; coordinates are relative to the glyph origin.
"""
import argparse
import ctypes as C
import hashlib
import textwrap
from pathlib import Path

import generate as G


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--font", type=Path, default=Path("/usr/share/fonts/noto-cjk/NotoSansCJK-Bold.ttc"))
    p.add_argument("--output", type=Path, default=Path(__file__).with_name("sign-outlines.inc"))
    a = p.parse_args()
    ft = G.freetype()
    library = C.c_void_p()
    G.checked(ft.FT_Init_FreeType(C.byref(library)))
    face = C.POINTER(G.Face)()
    G.checked(ft.FT_New_Face(library, str(a.font).encode(), 0, C.byref(face)))
    G.checked(ft.FT_Select_Charmap(face, 0x756E6963))
    out = ["// Generated by sign_generate.py; do not edit. Fixed sign artwork only.",
           "// Outlines derived from Noto Sans CJK JP Bold (SIL OFL 1.1).",
           f"// Font SHA-256: {hashlib.sha256(a.font.read_bytes()).hexdigest()}",
           "// Units: 1 = one em; y grows downward from the baseline."]
    names = []
    for i, ch in enumerate("居酒屋らーめん"):
        data = G.text_outline(ft, face, ch, 1.0, 0)[0]
        name = f"signGlyph{i}"
        names.append(name)
        out.append(f"\n// {ch}\nconstexpr char {name}[] =")
        lines = textwrap.wrap(data, width=110, break_long_words=False, break_on_hyphens=False)
        out.extend(f'    "{l}{" " if j < len(lines) - 1 else ""}"' for j, l in enumerate(lines))
        out[-1] += ";"
    out.append("\nconstexpr const char* signGlyphs[] = {" + ", ".join(names) + "};")
    ft.FT_Done_Face(face)
    ft.FT_Done_FreeType(library)
    a.output.write_text("\n".join(out) + "\n")
    print("wrote", a.output)


if __name__ == "__main__":
    main()
